import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { createServer } from 'vite'

const root = path.resolve(new URL('..', import.meta.url).pathname)
const target = path.join(root, 'src/data/articles.public.ts')
const checkOnly = process.argv.includes('--check')

const vite = await createServer({
  root,
  logLevel: 'silent',
  appType: 'custom',
  server: { middlewareMode: true },
})

let articlesData
try {
  ({ articlesData } = await vite.ssrLoadModule('/src/data/articleBuilder.ts'))
} finally {
  await vite.close()
}

const output = `// Generated by scripts/generate-public-articles.mjs. Do not edit by hand.\n`
  + `import type { ArticleRecord } from '../domain/types'\n\n`
  + `export const publicArticles: ArticleRecord[] = ${JSON.stringify(articlesData, null, 2)}\n`

if (checkOnly) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== output) {
    console.error('Generated public article registry is stale. Run: npm run generate:data')
    process.exit(1)
  }
  console.log(`Generated registry is current: ${articlesData.length} articles.`)
} else {
  await writeFile(target, output)
  console.log(`Generated ${path.relative(root, target)} with ${articlesData.length} clean articles.`)
}
